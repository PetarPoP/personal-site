"""Builds src/lib/cv/fonts.gen.ts: Archivo (from @fontsource/archivo, SIL OFL) for the CV PDF.

The Worker writes the PDF itself (src/lib/cv/pdf.ts), so it needs each font file plus the
character-to-glyph map and glyph widths. Latin and Latin-ext are merged into one font per
weight and compressed here, so building a CV costs the Worker almost no CPU.

Run after changing weights: python3 -m pip install fonttools && python3 scripts/cv-fonts.py
"""
import base64, io, json, zlib
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.merge import Merger

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'node_modules/@fontsource/archivo/files'
WEIGHTS = {'regular': 400, 'bold': 700, 'extrabold': 800}

out = ['// Generated by scripts/cv-fonts.py from @fontsource/archivo (SIL Open Font License). Do not edit.', '']
out.append('export type CvFont = { name: string; data: string; length: number; unitsPerEm: number; ascent: number; descent: number; capHeight: number; bbox: number[]; glyphs: number[] }')
out.append('')
for key, w in WEIGHTS.items():
    parts = []
    for sub in ('latin', 'latin-ext'):
        f = TTFont(SRC / f'archivo-{sub}-{w}-normal.woff')
        f.flavor = None
        b = io.BytesIO(); f.save(b); b.seek(0); parts.append(b)
    font = Merger().merge(parts)
    for t in ('GSUB', 'GPOS', 'GDEF', 'gasp'):
        if t in font: del font[t]
    b = io.BytesIO(); font.save(b); raw = b.getvalue()
    font = TTFont(io.BytesIO(raw))
    cmap = font.getBestCmap()
    order = font.getGlyphOrder()
    gid = {n: i for i, n in enumerate(order)}
    hmtx = font['hmtx']
    glyphs = []
    for cp in sorted(cmap):
        g = gid[cmap[cp]]
        glyphs += [cp, g, hmtx[cmap[cp]][0]]
    head, os2, hhea = font['head'], font['OS/2'], font['hhea']
    info = {
        'name': f'Archivo-{key.capitalize()}',
        'data': base64.b64encode(zlib.compress(raw, 9)).decode(),
        'length': len(raw),
        'unitsPerEm': head.unitsPerEm,
        'ascent': hhea.ascent,
        'descent': hhea.descent,
        'capHeight': getattr(os2, 'sCapHeight', 700) or 700,
        'bbox': [head.xMin, head.yMin, head.xMax, head.yMax],
        'glyphs': glyphs,
    }
    out.append(f'export const {key}: CvFont = {json.dumps(info, separators=(",", ":"))}')
    out.append('')
(ROOT / 'src/lib/cv/fonts.gen.ts').write_text('\n'.join(out))
print('wrote', (ROOT / 'src/lib/cv/fonts.gen.ts').stat().st_size, 'bytes')
